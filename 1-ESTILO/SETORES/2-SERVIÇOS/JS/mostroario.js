  const speeds = [0.6, 0.9, 0.5, 0.8, 0.7, 1.0];
  const rows = [];

  imageSets.forEach((set, idx) => {
    const row = document.getElementById('row' + (idx + 1));
    const allImages = [...set, ...set, ...set];
    allImages.forEach(src => {
      const img = document.createElement('img');
      img.src = src;
      img.alt = '';
      row.appendChild(img);
    });
    rows.push({ el: row, x: 0, speed: speeds[idx] });
  });

  function animate() {
    rows.forEach(r => {
      r.x -= r.speed;
      const firstImg = r.el.querySelector('img');
      if (firstImg) {
        const imgWidth = firstImg.offsetWidth + 12;
        const totalSetWidth = imgWidth * (imageSets[rows.indexOf(r)].length);
        if (Math.abs(r.x) >= totalSetWidth) {
          r.x += totalSetWidth;
        }
      }
      r.el.style.transform = 'translateX(' + r.x + 'px)';
    });
    requestAnimationFrame(animate);
  }

  animate();